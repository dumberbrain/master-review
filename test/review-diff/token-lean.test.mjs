import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { test } from 'node:test';
import { patchBatches, patchView, ruleDetails, ruleIndex } from '../../.claude/skills/review-diff/lib/digest.mjs';
import { precisionFilter, validateFindings } from '../../.claude/skills/review-diff/lib/findings.mjs';
import { buildMr, parseGitDiff } from '../../.claude/skills/review-diff/lib/merge-request.mjs';
import { loadRuleSet, parseRuleFile } from '../../.claude/skills/review-diff/lib/rules.mjs';
import { triageFile } from '../../.claude/skills/review-diff/lib/triage.mjs';
import { DIFF_SKILL, lines, runNode, tempDir } from '../helpers.mjs';

const CLI = path.join(DIFF_SKILL, 'bin', 'review.mjs');
const rules = loadRuleSet();

function fileDiff(name, ...body) {
  return lines(`diff --git a/${name} b/${name}`, `--- a/${name}`, `+++ b/${name}`, ...body);
}

// --- triage ---------------------------------------------------------------------------------

test('triage skips whitespace-only changes and blank-line additions', () => {
  assert.equal(triageFile('a.js', '@@ -1,2 +1,2 @@\n-if (x) {\n-  y()\n+if (x)  {\n+    y()').skipped.reason, 'whitespace-only change');
  assert.equal(triageFile('a.js', '@@ -1 +1,3 @@\n a\n+\n+   ').skipped.reason, 'whitespace-only change');
  assert.equal(triageFile('a.js', '@@ -1 +1 @@\n-a\n+b').skipped, undefined);
});

test('triage skips files with a generated marker in their first lines only', () => {
  assert.match(triageFile('a.go', '@@ -0,0 +1,2 @@\n+// Code generated by protoc. DO NOT EDIT.\n+package a').skipped.reason, /generated/);
  assert.equal(triageFile('a.go', '@@ -40,0 +41,1 @@\n+// Code generated by protoc. DO NOT EDIT.').skipped, undefined);
});

test('triage tags risks from added code and path, and ranks tests lower', () => {
  const sql = triageFile('src/repo.js', '@@ -1 +1,2 @@\n a\n+db.query("SELECT * FROM users WHERE id = " + id)');
  assert.deepEqual(sql.risk, ['injection']);
  const auth = triageFile('src/auth/login.ts', '@@ -1 +1 @@\n-a\n+el.innerHTML = name');
  assert.deepEqual(auth.risk, ['auth', 'html']);
  const testFile = triageFile('src/auth/login.test.ts', '@@ -1 +1 @@\n-a\n+el.innerHTML = name');
  assert.ok(testFile.risk.includes('test'));
  assert.ok(testFile.score < auth.score);
  assert.ok(auth.score > sql.score);
});

test('buildMr records triage: risk and score on reviewable files, reason on skipped ones', () => {
  const mr = buildMr(
    { files: parseGitDiff(fileDiff('a.js', '@@ -1 +1 @@', '-x', '+  x') + fileDiff('b.js', '@@ -1 +1 @@', '-x', '+eval(x)')) },
    rules,
  );
  assert.equal(mr.files[0].skipped.reason, 'whitespace-only change');
  assert.deepEqual(mr.files[1].risk, ['injection']);
  assert.equal(typeof mr.files[1].score, 'number');
});

// --- digest ---------------------------------------------------------------------------------

test('patchView numbers commentable lines and leaves removed lines unnumbered', () => {
  const [f] = buildMr({ files: parseGitDiff(fileDiff('src/a.ts', '@@ -8,3 +8,3 @@ class A', ' keep', '-old', '+neu', ' tail')) }, rules).files;
  assert.equal(
    patchView(f, rules),
    ['### src/a.ts  [modified · rules: general, typescript]', '@@ class A', ' 8  keep', '   -old', ' 9 +neu', '10  tail'].join('\n'),
  );
});

test('patchBatches puts the riskiest file first and splits by size', () => {
  const big = Array.from({ length: 40 }, (_, i) => `+const v${i} = ${i};`);
  const files = buildMr(
    { files: parseGitDiff(fileDiff('plain.js', '@@ -0,0 +1,40 @@', ...big) + fileDiff('risky.js', '@@ -1 +1 @@', '-a', '+eval(a)')) },
    rules,
  ).files;
  const one = patchBatches(files, rules);
  assert.equal(one.length, 1);
  assert.deepEqual(one[0].files, ['risky.js', 'plain.js']);
  const split = patchBatches(files, rules, 200);
  assert.deepEqual(split.map((b) => b.files), [['risky.js'], ['plain.js']]);
});

test('ruleIndex has one line per active rule of the wanted files, with override severity', () => {
  const rs = loadRuleSet();
  rs.byId.get('JS-001').severity = 'blocker';
  rs.byId.get('JS-002').status = 'retired';
  const { text, rules: count } = ruleIndex(rs, ['patterns-dev/javascript.md']);
  assert.match(text, /^- JS-001 blocker · Loose equality — /m);
  assert.doesNotMatch(text, /JS-002/);
  assert.doesNotMatch(text, /GEN-/);
  assert.equal(count, text.split('\n').filter((l) => l.startsWith('- ')).length);
  const full = fs.readFileSync(rs.files.find((f) => f.id === 'patterns-dev/javascript.md').path, 'utf8');
  assert.ok(text.length < full.length / 2, 'the index is much smaller than the rule file');
});

test('parseRuleFile keeps the first code block of a rule as its example', () => {
  const r = parseRuleFile('### A-001 — T\n\n- **why**: w\n\n```text\nbad: x\ngood: y\n```\n\n```text\nsecond\n```\n\n### A-002 — U\n').rules;
  assert.equal(r[0].example, 'bad: x\ngood: y');
  assert.equal(r[1].example, undefined);
});

test('ruleDetails returns why, fix and example, and lists unknown ids', () => {
  const { rules: d, unknown } = ruleDetails(rules, ['GEN-013', 'NOPE-1']);
  assert.equal(d['GEN-013'].severity, 'major');
  assert.match(d['GEN-013'].why, /\S/);
  assert.match(d['GEN-013'].fix, /\S/);
  assert.match(d['GEN-013'].example, /^bad:/);
  assert.deepEqual(unknown, ['NOPE-1']);
});

test('rule command prints details and exits 1 on an unknown id', (t) => {
  const dir = tempDir(t);
  const ok = runNode(CLI, ['rule', 'JS-001'], { cwd: dir });
  assert.equal(ok.status, 0, ok.stderr);
  assert.equal(ok.json['JS-001'].title, 'Loose equality');
  const bad = runNode(CLI, ['rule', 'JS-001', 'NOPE-1'], { cwd: dir });
  assert.equal(bad.status, 1);
  assert.deepEqual(bad.json.unknown, ['NOPE-1']);
});

test('parse removes patch batches left over from an earlier run', (t) => {
  const dir = tempDir(t);
  const p = (n) => path.join(dir, n);
  fs.writeFileSync(p('in.diff'), fileDiff('a.js', '@@ -1 +1 @@', '-a', '+b'));
  fs.mkdirSync(p('patches'));
  fs.writeFileSync(p('patches/07.md'), 'stale');
  fs.writeFileSync(p('patches/notes.txt'), 'mine');
  const r = runNode(CLI, ['parse', p('in.diff'), '--out', p('mr.json')]);
  assert.equal(r.status, 0, r.stderr);
  assert.deepEqual(fs.readdirSync(p('patches')).sort(), ['01.md', 'notes.txt']);
});

// --- precision ------------------------------------------------------------------------------

test('precisionFilter drops low confidence and nits over the cap, keeping the most confident', () => {
  const f = (id, severity, confidence) => ({ id, severity, confidence });
  const { kept, dropped } = precisionFilter(
    [f(1, 'major', 'low'), f(2, 'suggestion', 'medium'), f(3, 'suggestion', 'high'), f(4, 'suggestion', 'medium'), f(5, 'minor', 'medium')],
    { maxSuggestions: 2 },
  );
  assert.deepEqual(kept.map((x) => x.id), [2, 3, 5]);
  assert.deepEqual(dropped.map((x) => [x.id, x.dropReason]), [[1, 'low confidence'], [4, 'over the limit of 2 suggestions']]);
});

test('validate rejects an unknown confidence and reports dropped findings separately', () => {
  const mr = buildMr({ platform: 'github', files: parseGitDiff(fileDiff('src/a.js', '@@ -1 +1,2 @@', ' a', '+if (a == 1) b();')) }, rules);
  const base = { path: 'src/a.js', line: 2, ruleId: 'JS-001', title: 't', body: 'b' };
  const bad = validateFindings(mr, [{ ...base, confidence: 'sure' }], rules);
  assert.match(bad.invalid[0].error, /invalid confidence sure/);
  const { report } = validateFindings(mr, [{ ...base, confidence: 'high' }, { ...base, title: 'u', confidence: 'low' }], rules);
  assert.equal(report.findings.length, 1);
  assert.equal(report.findings[0].confidence, 'high');
  assert.equal(report.dropped.length, 1);
  assert.equal(report.summary.bySeverity.minor, 1);
});
